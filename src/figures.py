def _need(path: Path, produced_by: str) -> Path:
    if not path.is_file():
        raise SystemExit(f"{path} not found. Run {produced_by} first.")
    return path


def _tsv(path: Path, produced_by: str) -> pd.DataFrame:
    return pd.read_csv(_need(path, produced_by), sep="\t")


def _load_genome_seqs(manifest: pd.DataFrame) -> dict[str, str]:
    """Accession -> upper-case genome string, in manifest order.

    Uses `src.conservation.load_genome` so the sequence normalisation (case, line
    joining, ambiguity symbols left intact) is identical to stage 3's.
    """
    from src.conservation import load_genome

    out: dict[str, str] = {}
    for row in manifest.itertuples(index=False):
        out[str(row.accession)] = load_genome(PROJECT_ROOT / str(row.fasta_path))
    return out



    top = max(int(counts.max()) if len(counts) else 1, d["n_missing_year"])
    axy.hist(yrs, bins=bins, color=VERMILLION, edgecolor="white", lw=0.6, zorder=3)
    axy.set_xlim(bins[0] - 1.5, bins[-1] + 1.5)
    axy.set_xticks(np.arange(np.ceil(lo / 10) * 10, hi + 11, 10))
    axy.set_ylim(0, int(counts.max()) + 1.35 if len(counts) else 2.0)
    axy.set_yticks(np.arange(0, int(counts.max()) + 1) if len(counts) else [0])
    axy.set_xlabel("collection year", labelpad=2)
    axy.set_ylabel("carriers", labelpad=2)
    axy.grid(axis="y", color=FAINT, lw=0.4, alpha=0.5)
    axy.set_axisbelow(True)
    axy.text(0.0, 1.05, "%d of %d carriers are dated  —  note the two y scales"
             % (d["n_with_year"], d["n_carriers"]), transform=axy.transAxes,
             fontsize=5.5, color=MUTED, ha="left", va="bottom")

    axu.bar([0], [d["n_missing_year"]], width=0.62, color="none",
            edgecolor=MUTED, lw=0.8, hatch="////", zorder=3)

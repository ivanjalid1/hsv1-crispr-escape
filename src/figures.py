def fig2_data() -> dict:
    """Per-genome presence of the published lead pair across all 183 isolates.

    The per-genome presence VECTORS are in no results file. `absent_in` in
    `results/sacas9_benchmark_pool.tsv` and `results/*/conservation.tsv` is
    deliberately truncated to the first 25 accessions
    (`score_conservation(record_absences=25)`, and the same cap in
    `benchmark_sacas9`), so it under-reports ICP0g2, which is absent in 28. The
    matrix is therefore rebuilt from `data/raw/*.fasta` by calling the pipeline's own
    `src.benchmark_sacas9.presence_matrix` on a two-row pool -- stage-3 exact
    both-strand target-site semantics, same nuclease grammar, same genome order.

    The marginals it produces are checked against the published
    `conservation_complete_genomes`, and the joint against
    `joint_conservation` in `results/sacas9_benchmark_pairs.tsv`.
    """
    from src.benchmark_sacas9 import presence_matrix

    pool = _tsv(RESULTS_DIR / "sacas9_benchmark_pool.tsv",
                "run_pipeline.py --benchmark-sacas9")
    manifest = _tsv(DEFAULT_MANIFEST, "run_pipeline.py (stage 1)")
    pairs = _tsv(RESULTS_DIR / "sacas9_benchmark_pairs.tsv",
                 "run_pipeline.py --benchmark-sacas9")

    sub = pool[pool["guide_id"].isin([ICP0G2, ICP27G1])]
    if len(sub) != 2:
        raise SystemExit(f"Expected both lead guides in the stage-6 pool, found {len(sub)}.")
    nuclease = get_nuclease("sacas9", spacer_length=len(sub["protospacer"].iloc[0]))

    accessions, mat, index = presence_matrix(sub[["guide_id", "target_site"]],
                                             manifest, nuclease)
    icp0 = mat[:, index[ICP0G2]]
    icp27 = mat[:, index[ICP27G1]]

    published = dict(zip(pool["guide_id"], pool["conservation_complete_genomes"]))
    prow = pairs[(pairs["icp0_guide"] == ICP0G2) & (pairs["icp27_guide"] == ICP27G1)]
    if prow.empty:
        raise SystemExit("The published lead pair is missing from sacas9_benchmark_pairs.tsv.")

    marg = {ICP0G2: float(icp0.mean()), ICP27G1: float(icp27.mean())}
    joint = float((icp0 & icp27).mean())

    # Column order that makes the non-overlap visible: both present, then the
    # isolates each guide alone misses, then any missed by both.
    group = np.where(icp0 & icp27, 0, np.where(~icp0 & icp27, 1,
                     np.where(icp0 & ~icp27, 2, 3)))
    order = np.lexsort((np.arange(len(group)), group))

    return {
        "accessions": [str(a) for a in accessions],
        "icp0_present": icp0,
        "icp27_present": icp27,
        "order": order,
        "group": group,
        "n_genomes": int(mat.shape[0]),
        "marginals": marg,
        "published_marginals": {g: float(published[g]) for g in (ICP0G2, ICP27G1)},
        "product_of_marginals": float(marg[ICP0G2] * marg[ICP27G1]),
        "joint": joint,
        "published_joint": float(prow["joint_conservation"].iloc[0]),
        "n_both": int((icp0 & icp27).sum()),
        "n_icp0_only_absent": int((~icp0 & icp27).sum()),
        "n_icp27_only_absent": int((icp0 & ~icp27).sum()),
        "n_neither": int((~icp0 & ~icp27).sum()),
        "labels": {ICP0G2: "ICP0g2", ICP27G1: "ICP27g1"},
    }


def draw_fig2(d: dict) -> "plt.Figure":
    fig = plt.figure(figsize=(COL_IN, 3.15))
    gs = fig.add_gridspec(2, 1, height_ratios=[1.0, 1.0], hspace=0.88,
                          left=0.305, right=0.965, top=0.855, bottom=0.125)
    ax = fig.add_subplot(gs[0])
    ax2 = fig.add_subplot(gs[1])

    order = d["order"]
    rows = [(d["icp0_present"][order], ICP0G2, VERMILLION),
            (d["icp27_present"][order], ICP27G1, BLUE)]
    n = d["n_genomes"]
    b = d["n_both"]

    for r, (vec, gid, colour) in enumerate(rows):
        for x in np.flatnonzero(vec):
            ax.add_patch(Rectangle((x, r + 0.10), 1.0, 0.80, facecolor="#e2e2e2",
                                   edgecolor="none"))
        for x in np.flatnonzero(~vec):
            ax.add_patch(Rectangle((x, r + 0.10), 1.0, 0.80, facecolor=colour,
                                   edgecolor="none"))
    ax.set_xlim(0, n)
    # y grows downward so that row 0 (ICP0g2) is drawn on top; anything below the
    # matrix therefore has y > 2.
    ax.set_ylim(2.90, -0.05)
    ax.set_yticks([0.5, 1.5])
    ax.set_yticklabels([d["labels"][ICP0G2], d["labels"][ICP27G1]])
    ax.set_xticks([])
    for s in ("left", "bottom"):
        ax.spines[s].set_visible(False)
    ax.tick_params(axis="both", length=0, pad=2)
    ax.set_xlabel("183 complete HSV-1 genomes, by failure pattern", labelpad=1)

    ax.annotate("", xy=(b, 2.06), xytext=(n, 2.06),
                arrowprops=dict(arrowstyle="|-|,widthA=0.20,widthB=0.20",
                                lw=0.7, color=INK, shrinkA=0, shrinkB=0))
    ax.annotate("", xy=(0, 2.06), xytext=(b, 2.06),
                arrowprops=dict(arrowstyle="|-|,widthA=0.20,widthB=0.20",
                                lw=0.7, color="#9a9a9a", shrinkA=0, shrinkB=0))
    ax.text(n, 2.20,
            "%d missed — by one guide\nor the other, never both" % (n - b),
            ha="right", va="top", fontsize=5.7, color=INK)
    ax.text(0, 2.20, "both guides present\n(%d of %d)" % (b, n),
            ha="left", va="top", fontsize=5.7, color=MUTED)

    ax.legend(handles=[Line2D([], [], marker="s", ls="none", ms=4.2, mfc="#e2e2e2",
                              mec="none", label="present"),
                       Line2D([], [], marker="s", ls="none", ms=4.2, mfc=VERMILLION,
                              mec="none", label="ICP0g2 absent"),
                       Line2D([], [], marker="s", ls="none", ms=4.2, mfc=BLUE,
                              mec="none", label="ICP27g1 absent")],
              loc="lower left", bbox_to_anchor=(-0.005, 1.02), ncol=3,
              handletextpad=0.25, columnspacing=0.8, borderaxespad=0.0,
              fontsize=5.9)
    ax.set_title("A   Per-genome presence of the published lead pair",
                 loc="left", pad=17, x=TITLE_X)

    # Panel B -- the four coverage numbers, on an axis zoomed enough to separate the
    # product of marginals from the measured joint.
    items = [("ICP27g1 marginal", d["marginals"][ICP27G1], BLUE),
             ("ICP0g2 marginal", d["marginals"][ICP0G2], VERMILLION),
             ("product of marginals", d["product_of_marginals"], MUTED),
             ("measured joint", d["joint"], GREEN)]
    ypos = np.arange(len(items))[::-1]
    lo = 0.80
    for y, (label, val, colour) in zip(ypos, items):
        ax2.plot([lo, val], [y, y], color=colour, lw=1.6, solid_capstyle="butt",
                 zorder=2)
        ax2.plot([val], [y], marker="o", ms=4.2, mfc="white", mew=1.3, mec=colour,
                 zorder=3)
        ax2.text(val + 0.005, y, f"{val:.4f}", va="center", ha="left", fontsize=6.0,
                 color=INK)
    ax2.set_yticks(ypos)
    ax2.set_yticklabels([i[0] for i in items])
    ax2.set_xlim(lo, 1.045)
    ax2.set_ylim(-0.6, len(items) - 0.4)
    ax2.set_xticks([0.80, 0.85, 0.90, 0.95, 1.00])
    ax2.set_xlabel("fraction of the 183 genomes", labelpad=2)
    ax2.spines["left"].set_visible(False)
    ax2.spines["bottom"].set_bounds(lo, 1.0)
    ax2.tick_params(axis="y", length=0, pad=2)
    ax2.grid(axis="x", color=FAINT, lw=0.4, alpha=0.5)
    ax2.set_axisbelow(True)
    ax2.set_title("B   Coverage is not the product of the marginals",
                  loc="left", pad=4, x=TITLE_X)
    ax2.annotate("joint < product:\nthe two failures are\nanti-correlated,\n"
                 "not independent",
                 xy=(0.870, 0.5), xytext=(0.888, 0.62),
                 fontsize=5.7, color=INK, ha="left", va="center",
                 arrowprops=dict(arrowstyle="-", lw=0.6, color=MUTED,
                                 shrinkA=1, shrinkB=2))
    return fig



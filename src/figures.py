def save_figure(fig: "plt.Figure", number: int, outdir: Path) -> list[Path]:
    outdir.mkdir(parents=True, exist_ok=True)
    png = outdir / f"fig{number}.png"
    pdf = outdir / f"fig{number}.pdf"
    fig.savefig(png, dpi=300, format="png", metadata=_MPL_PNG_METADATA)
    fig.savefig(pdf, format="pdf", metadata=_MPL_PDF_METADATA)
    return [png, pdf]


def build(numbers=(1, 2, 3, 4, 5), outdir: Path = FIGURE_DIR) -> dict[int, list[Path]]:
    written: dict[int, list[Path]] = {}
    with plt.rc_context(RC):
        for n in numbers:
            data_fn, draw_fn, title = FIGURES[n]
            LOG.info("figure %d -- %s", n, title)
            fig = draw_fn(data_fn())
            written[n] = save_figure(fig, n, outdir)
            plt.close(fig)
            for p in written[n]:
                LOG.info("  wrote %s (%d bytes)", p, p.stat().st_size)
    return written


def _digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def add_arguments(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--outdir", type=Path, default=FIGURE_DIR,
                        help="directory for figN.png / figN.pdf (default: figures/)")
    parser.add_argument("--figure", type=int, action="append", choices=sorted(FIGURES),
                        help="render only this figure (repeatable; default: all five)")
    parser.add_argument("--check-deterministic", action="store_true",
                        help="render twice and verify the bytes are identical")
    parser.add_argument("--verbose", action="store_true")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    add_arguments(parser)
    args = parser.parse_args(argv)
    setup_logging(args.verbose)
    logging.getLogger().setLevel(logging.INFO)

    numbers = tuple(sorted(set(args.figure))) if args.figure else tuple(sorted(FIGURES))
    written = build(numbers, args.outdir)

    if args.check_deterministic:
        first = {p: _digest(p) for ps in written.values() for p in ps}
        build(numbers, args.outdir)
        bad = [str(p) for p, h in first.items() if _digest(p) != h]
        if bad:
            LOG.error("NOT deterministic: %s", ", ".join(bad))
            return 1
        LOG.info("deterministic: %d files reproduced byte-for-byte", len(first))

    print("\nWrote %d figure(s) to %s:" % (len(written), args.outdir))
    for n in sorted(written):
        for p in written[n]:
            print(f"  {p.relative_to(PROJECT_ROOT) if PROJECT_ROOT in p.parents else p}"
                  f"  {p.stat().st_size:,} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

def _single_substitution_variants(seqs: dict[str, str], target: str) -> dict[str, list[str]]:
    """Accession -> the target sites at exactly one substitution from `target`.

    Exact and complete for 1 mismatch by the pigeonhole principle: split the target
    in two halves, and a one-substitution copy must match one half verbatim, so
    anchoring on each half in turn cannot miss a hit. Both strands are searched, and
    hits are reported in the target's own orientation.
    """
    n = len(target)
    half = n // 2
    out: dict[str, list[str]] = {}
    for acc, seq in seqs.items():
        found: set[str] = set()
        for probe, orient in ((target, "+"), (revcomp(target), "-")):
            pblocks = (((probe[:half], 0), (probe[half:], half))
                       if orient == "+" else
                       ((probe[:n - half], 0), (probe[n - half:], n - half)))
            for block, off in pblocks:
                i = seq.find(block)
                while i != -1:
                    s = i - off
                    if 0 <= s and s + n <= len(seq):
                        cand = seq[s:s + n]
                        fwd = cand if orient == "+" else revcomp(cand)
                        if sum(1 for a, b in zip(fwd, target) if a != b) == 1:
                            found.add(fwd)
                    i = seq.find(block, i + 1)
        out[acc] = sorted(found)
    return out


def fig5_data() -> dict:
    """The recurrent single-nucleotide variant under the ICP0g2 spacer.

    Not in any results file: `absent_in` is truncated at 25 accessions and records
    only WHICH isolates lack the site, never what they carry instead. Both the
    identity of the variant and its carriers are therefore DISCOVERED here from
    `data/raw/*.fasta`, by enumerating every target site at exactly one substitution
    from ICP0g2's (both strands, pigeonhole-exact) across all 183 genomes and taking
    the most frequent. Nothing about the position or the base change is assumed.

    Carrier metadata is read from `data/manifest.tsv`; records with no country or no
    collection date are counted and shown as their own category rather than dropped.
    """
    pool = _tsv(RESULTS_DIR / "sacas9_benchmark_pool.tsv",
                "run_pipeline.py --benchmark-sacas9")
    manifest = _tsv(DEFAULT_MANIFEST, "run_pipeline.py (stage 1)")
    row = pool[pool["guide_id"] == ICP0G2]
    if row.empty:
        raise SystemExit(f"{ICP0G2} is missing from the stage-6 pool.")
    row = row.iloc[0]
    target = str(row["target_site"])
    spacer = str(row["protospacer"])
    pam = str(row["pam"])

    seqs = _load_genome_seqs(manifest)
    variants = _single_substitution_variants(seqs, target)

    present = {acc: (target in s) or (revcomp(target) in s) for acc, s in seqs.items()}
    counts: dict[str, list[str]] = {}
    for acc, vs in variants.items():
        for v in vs:
            counts.setdefault(v, []).append(acc)
    if not counts:
        raise SystemExit("No single-substitution variant of the ICP0g2 site was found.")
    variant, carriers = max(counts.items(), key=lambda kv: (len(kv[1]), kv[0]))
    carriers = sorted(carriers)

    diffs = [(i, a, b) for i, (a, b) in enumerate(zip(target, variant)) if a != b]
    if len(diffs) != 1:
        raise SystemExit("The dominant variant is not a single substitution.")
    idx0, ref_base, alt_base = diffs[0]

    absent = sorted(a for a, p in present.items() if not p)
    other_variant = sorted(set(absent) - set(carriers))
    other_detail = {a: variants[a] for a in other_variant if variants[a]}

    meta = manifest.set_index("accession")
    years, countries = {}, {}
    for acc in carriers:
        raw_date = meta.at[acc, "collection_date"] if acc in meta.index else None
        m = re.search(r"(1[89]\d{2}|20\d{2})", str(raw_date)) if pd.notna(raw_date) else None
        years[acc] = int(m.group(1)) if m else None
        raw_country = meta.at[acc, "country"] if acc in meta.index else None
        countries[acc] = (str(raw_country).split(":")[0].strip()
                          if pd.notna(raw_country) else None)

    n_year = sum(v is not None for v in years.values())
    n_country = sum(v is not None for v in countries.values())

    return {
        "guide_id": ICP0G2,
        "label": "ICP0g2",
        "spacer": spacer,
        "pam": pam,
        "target": target,
        "variant": variant,
        "variant_index0": idx0,
        "spacer_position": idx0 + 1,
        "ref_base": ref_base,
        "alt_base": alt_base,
        "ref_start": int(row["ref_start"]),
        "n_genomes": int(len(seqs)),
        "carriers": carriers,
        "n_carriers": len(carriers),
        "n_present": int(sum(present.values())),
        "n_absent": len(absent),
        "absent": absent,
        "other_absent": other_variant,
        "other_absent_variants": other_detail,
        "published_n_present": int(row["n_strains_present"]),
        "years": years,
        "countries": countries,
        "n_with_year": n_year,
        "n_missing_year": len(carriers) - n_year,
        "n_with_country": n_country,
        "n_missing_country": len(carriers) - n_country,
        "all_variant_counts": {v: len(a) for v, a in
                               sorted(counts.items(), key=lambda kv: -len(kv[1]))},
    }



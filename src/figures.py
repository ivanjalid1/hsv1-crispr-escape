"""Stage 9 -- the five publication figures.

Every number drawn by this module is either READ from a file in `results/` or
REGENERATED by calling the pipeline's own modules on the pipeline's own inputs.
Nothing is transcribed from a report's prose and nothing is hardcoded; the two
quantities that are not in any results file (the per-genome presence vectors of the
lead pair, and the identity of the recurrent ICP0g2 variant) are computed here from
`data/raw/*.fasta` through `src.benchmark_sacas9.presence_matrix` and an exact
pigeonhole search, and each figure's data function says so in its own docstring.

Layout
------
`figN_data()`  -> a plain dict of the values the figure plots, with provenance.
                  These are what `tests/test_figures.py` checks. They touch no
                  matplotlib state and can be called on their own.
`draw_figN(d)` -> a matplotlib Figure built from that dict.
`main()`       -> writes figures/figN.png (300 dpi) and figures/figN.pdf (vector).

Determinism
-----------
Output is byte-identical on re-run: no timestamp or per-run metadata is written into
either format (`_MPL_METADATA`), the bundled DejaVu font is used rather than a system
font, hash-salted ids are pinned, and nothing in the module samples a random number.
`python src/figures.py --check-deterministic` renders twice and compares digests.

Accessibility
-------------
Marks use the Okabe-Ito colourblind-safe palette; every coloured series is also
distinguished by marker or line style and carries a direct label or legend entry, so
identity is never conveyed by colour alone.
"""


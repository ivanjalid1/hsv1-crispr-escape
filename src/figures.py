def fig1_data() -> dict:
    """P(escape) versus guide count k: point estimate and certifiable bound.

    Point estimate: read verbatim from `results/escape_k_curve.tsv`
    (`p_escape_best`), which stage 7 wrote.

    Certifiable bound: NOT stored in any results file -- stage 7 renders it straight
    into section 7.1 of `results/escape_model_report.md`. It is regenerated here with
    stage 7's own arithmetic and stage 7's own function:

        absences_i = n_strains_total - n_strains_present   (results/sacas9-20nt/
                                                            conservation.tsv)
        u_i        = binomial_upper_bound(absences_i, N)   (src.escape, Clopper-
                                                            Pearson 95% upper limit)
        bound(S)   = PROD_i [ u_i + (1 - u_i) * q_i ]      (q_i = q_site, results/
                                                            escape_site_parameters.tsv)

    which is line-for-line the `absence_upper` / `floor_rows` block of
    `src.escape.assemble_context`. `tests/test_figures.py` checks the regenerated
    values against the numbers stage 7 printed in its own report.

    The k=1 sites of the best sets are all present in 183/183 genomes, so every u_i
    is the same rule-of-three bound, 0.0162 -- the "site absent in 0/183 treated as
    having population absence frequency 0.0162" of the figure specification. That is
    a property of the data, read off it, not an assumption applied to it.
    """
    curve = _tsv(RESULTS_DIR / "escape_k_curve.tsv", "run_pipeline.py --escape")
    params = _tsv(RESULTS_DIR / "escape_site_parameters.tsv",
                  "run_pipeline.py --escape")
    cons = _tsv(RESULTS_DIR / "sacas9-20nt" / "conservation.tsv",
                "run_pipeline.py --nuclease sacas9 --spacer-length 20 --skip-fetch")

    q = dict(zip(params["guide_id"], params["q_site"]))
    present = dict(zip(cons["guide_id"], cons["n_strains_present"]))
    n_genomes = int(cons["n_strains_total"].iloc[0])

    ub_cache: dict[int, float] = {}

    def absence_upper(absences: int) -> float:
        if absences not in ub_cache:
            ub_cache[absences] = binomial_upper_bound(absences, n_genomes)
        return ub_cache[absences]

    ks, point, bound, absences_per_k = [], [], [], []
    for row in curve.itertuples(index=False):
        guides = str(row.guides).split(";")
        missing = [g for g in guides if g not in q or g not in present]
        if missing:
            raise SystemExit(
                f"k={row.k}: no q_site/conservation for {missing}; the k-curve and "
                "the site tables come from different runs.")
        ub = 1.0
        absent_counts = []
        for g in guides:
            a = n_genomes - int(present[g])
            absent_counts.append(a)
            u = absence_upper(a)
            ub *= u + (1.0 - u) * float(q[g])
        ks.append(int(row.k))
        point.append(float(row.p_escape_best))
        bound.append(ub)
        absences_per_k.append(absent_counts)

    ks_a = np.asarray(ks, dtype=int)
    point_a = np.asarray(point, dtype=float)
    bound_a = np.asarray(bound, dtype=float)

    def first_below(vals: np.ndarray, t: float) -> int | None:
        hit = np.flatnonzero(vals < t)
        return int(ks_a[hit[0]]) if hit.size else None

    crossings = {t: {"point": first_below(point_a, t), "bound": first_below(bound_a, t)}
                 for t in FIG1_THRESHOLDS}

    return {
        "k": ks_a,
        "p_point": point_a,
        "p_bound": bound_a,
        "n_genomes": n_genomes,
        "rule_of_three": absence_upper(0),
        "absences_per_k": absences_per_k,
        "thresholds": tuple(FIG1_THRESHOLDS),
        "crossings": crossings,
        "guides": [str(g) for g in curve["guides"]],
    }


def draw_fig1(d: dict) -> "plt.Figure":
    fig, ax = plt.subplots(figsize=(COL_IN, 2.85))
    k = d["k"]

    for t in d["thresholds"]:
        ax.axhline(t, color="#b4b4b4", lw=0.8, ls=(0, (4, 3)), zorder=1,
                   xmax=0.90)
        ax.text(k[-1] + 0.42, t, f"$10^{{{int(round(np.log10(t)))}}}$",
                va="center", ha="left", fontsize=6, color=MUTED, clip_on=False)

    ax.plot(k, d["p_bound"], color=VERMILLION, lw=1.5, ls=(0, (5, 2)),
            marker="s", ms=3.6, mfc="white", mew=1.2, mec=VERMILLION,
            zorder=3, label="certifiable bound (95% CI)")
    ax.plot(k, d["p_point"], color=BLUE, lw=1.5, marker="o", ms=3.8,
            mfc="white", mew=1.2, mec=BLUE, zorder=4,
            label="point estimate (measured absences)")

    ax.set_yscale("log")
    ax.set_xlabel("number of guides, $k$")
    ax.set_ylabel("P(escape) per exposed viral genome")
    ax.set_xticks(k)
    ax.set_xlim(k[0] - 0.35, k[-1] + 1.15)

    lo = min(d["p_point"].min(), d["p_bound"].min())
    hi = max(d["p_point"].max(), d["p_bound"].max())
    ax.set_ylim(10 ** (np.floor(np.log10(lo)) - 0.6), 10 ** (np.ceil(np.log10(hi)) + 0.4))
    ax.set_yticks([10.0 ** e for e in range(int(np.floor(np.log10(lo))),
                                            int(np.ceil(np.log10(hi))) + 1, 3)])
    ax.grid(axis="y", color=FAINT, lw=0.4, alpha=0.45, zorder=0)
    ax.set_axisbelow(True)

    # Annotate the 1e-6 crossings -- the paper's headline: one more guide is needed
    # before the corpus can certify what the point estimate already claims.
    t = 1e-6
    kp = d["crossings"][t]["point"]
    kb = d["crossings"][t]["bound"]
    if kp is not None and kb is not None:
        yp = d["p_point"][list(k).index(kp)]
        yb = d["p_bound"][list(k).index(kb)]
        for kk, yy, col in ((kp, yp, BLUE), (kb, yb, VERMILLION)):
            ax.plot([kk], [yy], marker="o", ms=9.0, mfc="none", mec=col,
                    mew=1.0, zorder=5)
        ax.annotate(f"point estimate reaches\n$10^{{-6}}$ at $k$ = {kp}",
                    xy=(kp, yp), xytext=(kp - 1.95, yp / 400),
                    fontsize=6, color=BLUE, ha="left", va="top",
                    arrowprops=dict(arrowstyle="-", lw=0.7, color=BLUE,
                                    shrinkA=1, shrinkB=6))
        ax.annotate(f"the corpus can certify it\nonly at $k$ = {kb}", xy=(kb, yb),
                    xytext=(kb + 1.05, yb * 320), fontsize=6, color=VERMILLION,
                    ha="left", va="bottom",
                    arrowprops=dict(arrowstyle="-", lw=0.7, color=VERMILLION,
                                    shrinkA=1, shrinkB=6))

    ax.legend(loc="lower left", handlelength=2.0, labelspacing=0.6,
              borderaxespad=0.35, handletextpad=0.5)
    ax.set_title("Resolution floor of a %d-genome corpus" % d["n_genomes"],
                 loc="left", pad=5)
    fig.text(0.012, 0.018,
             "A site absent in 0/%d isolates is still consistent with a population\n"
             "absence frequency up to %.4f (Clopper–Pearson 95%% upper limit); the\n"
             "bound re-runs the escape model with every site set to that value."
             % (d["n_genomes"], d["rule_of_three"]),
             fontsize=5.3, color=MUTED, va="bottom", ha="left", linespacing=1.4)
    fig.subplots_adjust(left=0.175, right=0.935, top=0.915, bottom=0.295)
    return fig


